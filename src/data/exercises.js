export function exerciseGroup(ex) {
  if (ex.cat === 'mobility') return 'mobility'
  if (ex.type === 'cardio') return 'cardio'
  const m = ex.primary[0]
  const g = MUSCLE_GROUPS.find((g) => g.id === m || g.muscles?.includes(m))
  if (g) return g.id
  if (m === 'traps') return 'back'
  return 'core'
}
